#!/usr/bin/env bash
set -euo pipefail

# mobile_dev version-pin contract (SDD plan 2026-10-10-mobile-dev-wsl-linux-macos,
# Task 1): .chezmoidata.yaml's versions.* table has no generic "every pin has a
# scripts/update-versions.sh handler" contract (tests/update_guardrail_versions.sh
# checks the OPPOSITE for guardrail.version: that the script must never touch
# it). This is the minimal check for the two pins this task added:
#
#   - versions.maestro_version / versions.maestro_sha256 - a real exact-version
#     pin + a real vendor-published sha256 (NOT computed from a fresh download
#     here - read from mobile-dev-inc/homebrew-tap's own formula, generated by
#     JReleaser at release time), because the vendor's own
#     `curl -fsSL https://get.maestro.mobile.dev | bash` installer does not
#     verify a checksum of what it fetches (only `unzip -qt`, a corruption
#     check). scripts/update-versions.sh must carry a handler that keeps it
#     current.
#   - versions.jdk_version - a deliberate hand pin (like node_major), which
#     scripts/update-versions.sh documents but does not try to "resolve
#     latest" for (Java's version floor is a design decision, not a moving
#     target).

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
data_file="$repo_root/.chezmoidata.yaml"
version_script="$repo_root/scripts/update-versions.sh"

. "$repo_root/tests/lib.sh"

[ -f "$data_file" ] || fail ".chezmoidata.yaml missing"
[ -f "$version_script" ] || fail "scripts/update-versions.sh missing"

# 1. jdk_version: a bare integer >= 17 (Maestro's own "Java 17 or higher").
jdk="$(sed -n 's/^  jdk_version: \([0-9][0-9]*\)$/\1/p' "$data_file")"
if [ -z "$jdk" ]; then
    fail ".chezmoidata.yaml: no 'jdk_version: <int>' pin found"
elif [ "$jdk" -lt 17 ]; then
    fail ".chezmoidata.yaml: jdk_version=$jdk is below Maestro's Java 17 floor"
else
    pass
fi

# 2. maestro_version: an exact X.Y.Z pin, never "latest".
maestro_ver="$(sed -n 's/^  maestro_version: "\([^"]*\)"$/\1/p' "$data_file")"
case "$maestro_ver" in
    [0-9]*.[0-9]*.[0-9]*) pass ;;
    *) fail ".chezmoidata.yaml: maestro_version='$maestro_ver' is not an exact X.Y.Z pin" ;;
esac

# 3. maestro_sha256: a real 64-char lowercase hex digest, not a placeholder.
#    The full 64 characters are checked (not just a prefix) - a bash regex
#    anchored at both ends, the same style tests/run.sh uses for its own
#    format check.
maestro_sha="$(sed -n 's/^  maestro_sha256: "\([^"]*\)"$/\1/p' "$data_file")"
if [[ "$maestro_sha" =~ ^[0-9a-f]{64}$ ]]; then
    pass
else
    fail ".chezmoidata.yaml: maestro_sha256='$maestro_sha' is not 64 lowercase hex characters"
fi

# 4. scripts/update-versions.sh carries a real handler for the Maestro pin -
#    not just a grep for its own name, but the shape every other network pin
#    here uses: net_timeout, and both .chezmoidata.yaml keys rewritten together.
require "$version_script" 'net_timeout 60 curl -fsSL "https://raw.githubusercontent.com/mobile-dev-inc/homebrew-tap/master/Formula/maestro.rb"'
require "$version_script" 's|^  maestro_version: .*|  maestro_version: \"$MAESTRO_LATEST\"|'
require "$version_script" 's|^  maestro_sha256: .*|  maestro_sha256: \"$MAESTRO_SHA\"|'

# 5. jdk_version is documented as a deliberate non-cron pin, and the script
#    must never silently start "resolving latest JDK" for it.
require "$version_script" 'jdk_version'
forbid "$version_script" 'JDK_LATEST'

# 6. Executable check: source the REAL scripts/update-versions.sh and call
#    its real parse_maestro_version/parse_maestro_sha256 functions against a
#    fixture of mobile-dev-inc/homebrew-tap's Formula/maestro.rb (captured
#    2026-10-10) - not a hand-duplicated copy of the sed patterns. A
#    duplicate copy would keep passing even if the real parsing in
#    update-versions.sh were edited (correctly or incorrectly) without a
#    matching edit here; sourcing the real file closes that gap (see
#    docs/invariants.md #14). update-versions.sh detects being sourced and
#    returns right after defining these functions, before any network call
#    or file write and before it sets `set -e` on us.
# shellcheck disable=SC1090
. "$version_script"
fixture='# Generated with JReleaser 1.13.1 at 2026-09-29T13:34:16.745212209Z

class Maestro < Formula
  desc "The easiest way to automate UI testing for your mobile app"
  homepage "https://maestro.mobile.dev"
  url "https://github.com/mobile-dev-inc/maestro/releases/download/cli-2.11.0/maestro.zip"
  version "2.11.0"
  sha256 "5384593cb4e7a106489e75a821d157dd43f4e438df6bc308b72e82c685e1283a"
  license "Apache-2.0"
'
got_ver="$(printf '%s\n' "$fixture" | parse_maestro_version)"
got_sha="$(printf '%s\n' "$fixture" | parse_maestro_sha256)"
[ "$got_ver" = "2.11.0" ] || fail "parse_maestro_version: expected version 2.11.0, got '$got_ver'"
[ "$got_sha" = "5384593cb4e7a106489e75a821d157dd43f4e438df6bc308b72e82c685e1283a" ] ||
    fail "parse_maestro_sha256: expected the pinned sha256, got '$got_sha'"
[ "$got_ver" = "2.11.0" ] && [ "$got_sha" = "5384593cb4e7a106489e75a821d157dd43f4e438df6bc308b72e82c685e1283a" ] && pass

finish
